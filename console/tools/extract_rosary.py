#!/usr/bin/env python3
"""Regenerate lpsconsole/rosary_texts.py from the Companion's lps_companion.cpp.

Usage: python3 tools/extract_rosary.py /path/to/LPS-Companion-PicoCalc/src/lps_companion.cpp
The texts are copied verbatim so the console Rosary matches the device.
"""
import re
import sys
import pprint
from pathlib import Path

STR = r'"((?:[^"\\]|\\.)*)"'


def unescape(s):
    return s.encode("latin-1", "backslashreplace").decode("unicode_escape").encode("latin-1").decode("utf-8") if "\\" in s else s


def strings(chunk):
    return [unescape(s) for s in re.findall(STR, chunk)]


def function_body(src, name):
    start = src.index(name + "(")
    return src[start:src.index("\n    }\n", start)]


def table(body, lang):
    m = re.search(r"static constexpr const char\* %s\[4\]\[5\]=\{(.*?)\};" % lang, body, re.S)
    flat = strings(m.group(1))
    assert len(flat) == 20, len(flat)
    return [flat[i * 5:(i + 1) * 5] for i in range(4)]


def main(path):
    src = Path(path).read_text(encoding="utf-8")
    out = {}
    for fn in ("mysteryName", "scripture", "meditation"):
        body = function_body(src, "const char* " + fn)
        out[fn] = {"en": table(body, "en"), "fr": table(body, "fr")}
    sets = function_body(src, "const char* mysterySetName")
    out["mysterySetName"] = {
        "en": strings(re.search(r"en\[\]=\{(.*?)\}", sets).group(1)),
        "fr": strings(re.search(r"fr\[\]=\{(.*?)\}", sets).group(1)),
    }
    for fn, key in (("const char* rosaryText", "text"), ("const char* rosaryPartName", "partName")):
        body = function_body(src, fn)
        parts = {}
        for line in body.splitlines():
            cases = re.findall(r"case RosaryPart::(\w+):", line)
            m = re.search(r"return tr\(" + STR + "," + STR + r"\);", line)
            if cases and m:
                for c in cases:
                    parts[c] = {"en": unescape(m.group(1)), "fr": unescape(m.group(2))}
        out[key] = parts
    with open(Path(__file__).resolve().parent.parent / "lpsconsole" / "rosary_texts.py", "w", encoding="utf-8") as f:
        f.write('"""Rosary texts copied verbatim from LPS Companion v1.11 (src/lps_companion.cpp).\n\n'
                'Generated by tools/extract_rosary.py - do not edit by hand."""\n\n')
        for k, v in out.items():
            f.write("%s = %s\n\n" % (k.upper() if k in ("text", "partName") else k, pprint.pformat(v, width=120)))
    print("ok")


if __name__ == "__main__":
    main(sys.argv[1])
